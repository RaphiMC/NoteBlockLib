package net.raphimc.noteblocklib.util;

public final class StringUtil {

    private StringUtil() {
    }

    public static String formatDuration(final long durationMillis) {
        if (durationMillis < 0) {
            throw new IllegalArgumentException("Duration millis must be >= 0: " + durationMillis);
        }

        final long totalSeconds = durationMillis / 1000;
        final long hours = totalSeconds / 3600;
        final long minutes = (totalSeconds % 3600) / 60;
        final long seconds = totalSeconds % 60;
        if (hours > 0) {
            return String.format("%d:%02d:%02d", hours, minutes, seconds);
        } else {
            return String.format("%02d:%02d", minutes, seconds);
        }
    }

}
